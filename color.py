# Format: \033[<style>;<text_color>;<bg_color>m
# Reset code: \033[0m

RED = "\033[31m"
GREEN = "\033[32m"
YELLOW = "\033[33m"
BLUE = "\033[34m"
MAGENTA = "\033[35m"
CYAN = "\033[36m"
RESET = "\033[0m"

# Example:
print(f"{RED}This text is red{RESET}")
print(f"{GREEN}This text is green{RESET}")
